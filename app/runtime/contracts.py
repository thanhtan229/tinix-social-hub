from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class BrowserRuntime(Protocol):
    def open(self,account:dict[str,Any])->dict[str,Any]:...
    def status(self,account_id:str|None=None)->Any:...
    def close(self,account_id:str)->bool:...
    def close_all(self)->int:...


@runtime_checkable
class ManagedStorage(Protocol):
    root:Path
    def safe_path(self,relative_path:str)->Path:...
    def resolve_existing(self,relative_path:str)->Path:...


@runtime_checkable
class SecretStore(Protocol):
    def protect(self,value:str)->str:...
    def unprotect(self,value:str)->str:...


@runtime_checkable
class StateDatabase(Protocol):
    def initialize(self)->bool:...
    def connection(self)->Any:...
    def ping(self)->dict[str,Any]:...


@runtime_checkable
class DurableQueue(Protocol):
    def claim_next(self)->dict[str,Any]|None:...
    def recover_interrupted(self)->int:...
    def release_due(self)->int:...
    def transition(self,job_id:str,target:Any,**kwargs:Any)->dict[str,Any]:...
